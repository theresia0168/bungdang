/** 마우스를 올리면 바로 뜨는 설명 카드 */
const CARD_W = 330;

export function Tip({ k, s, children, place = 'down' }: { k: StatKey; s?: GameState; children: ReactNode; place?: 'down' | 'down-end' | 'right' }) {
  const g = STAT_GUIDE[k];
  const [pos, setPos] = useState<CSSProperties | null>(null);
  const now = s && g.now ? g.now(s) : [];

  const show = (el: HTMLElement) => {
    const r = el.getBoundingClientRect();
    const W = window.innerWidth;
    const H = window.innerHeight;
    let left = place === 'right' ? r.right + 8 : place === 'down-end' ? r.right - CARD_W : r.left;
    left = Math.max(8, Math.min(W - CARD_W - 8, left));
    const top = place === 'right' ? r.top : r.bottom + 6;
    const upward = top > H * 0.55;
    setPos(upward ? { left, bottom: H - (place === 'right' ? r.bottom : r.top - 6), maxHeight: r.top - 16 } : { left, top, maxHeight: H - top - 10 });
  };

  return (
    <span
      className="tip"
      tabIndex={0}
      onMouseEnter={(e) => show(e.currentTarget)}
      onFocus={(e) => show(e.currentTarget)}
      onMouseLeave={() => setPos(null)}
      onBlur={() => setPos(null)}
    >
      {children}
      {pos && (
      <span className="tip-card" role="tooltip" style={pos}>
        <span className="tip-title">
          {g.name}
          {g.hanja && <small> {g.hanja}</small>} <em>{g.caption}</em>
        </span>
        <span className="tip-what">{g.what}</span>
        {now.length > 0 && (
          <span className="tip-now">
            <b>지금</b>
            {now.map((x, i) => (
              <span key={i}>{x}</span>
            ))}
          </span>
        )}
        <span className="tip-sec">
          <b>쓰이는 곳</b>
          {g.uses.map((x, i) => (
            <span key={i}>· {x}</span>
          ))}
        </span>
        <span className="tip-sec">
          <b>올리는 법</b>
          {g.gain.map((x, i) => (
            <span key={i}>· {x}</span>
          ))}
        </span>
        {g.lose && (
          <span className="tip-sec">
            <b>잃는 경우</b>
            {g.lose.map((x, i) => (
              <span key={i}>· {x}</span>
            ))}
          </span>
        )}
      </span>
      )}
    </span>
  );
}

